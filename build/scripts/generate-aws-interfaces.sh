#!/bin/bash -ex

[ "$#" -eq 2 ] || { echo "usage: ${0} <service-name> <interface-name>"; exit 1; }

SERVICE_NAME="${1}"
INTERFACE_NAME="${2}"

PACKAGE_NAME="github.com/aws/aws-sdk-go-v2/service/${SERVICE_NAME}"

# Resolve the version already selected in go.mod. Using 'go get' here would
# upgrade the module to its latest release and rewrite go.mod mid-build, which
# makes every build non-reproducible: interfaces get generated against whatever
# AWS published most recently rather than the pinned version, so an upstream
# release can change generated code, and break tests that serialize SDK types,
# with no corresponding commit to this repository.
go mod download "${PACKAGE_NAME}"
AWS_SDK_DIR=$(go list -m -f '{{.Dir}}' "${PACKAGE_NAME}")

OUTPUT_FILE="../${SERVICE_NAME}.go"

"${GOBIN}/ifacemaker" -f "${AWS_SDK_DIR}/*.go" -s Client -i "${INTERFACE_NAME}" -p awsapi \
    -y "${INTERFACE_NAME} provides an interface to the AWS ${INTERFACE_NAME} service." \
    -c "Code generated by ifacemaker; DO NOT EDIT." \
    -m "${PACKAGE_NAME}" > "${OUTPUT_FILE}"

# The generated interface refers to SDK types both through the dot import
# (e.g. Options) and through the package qualifier (e.g. ssm.PutParameterInput).
# ifacemaker only emits the dot import and relies on golang.org/x/tools/imports
# to add the qualified import. Since x/tools v0.48.0 (https://go.dev/cl/767881),
# imports resolves packages from the gopls module cache index when one exists
# instead of scanning GOMODCACHE, and in that case it may not add the import.
# Add it explicitly when missing so the output doesn't depend on local state.
if ! grep -qxF "	\"${PACKAGE_NAME}\"" "${OUTPUT_FILE}"; then
    awk -v dot_import="	. \"${PACKAGE_NAME}\"" -v named_import="	\"${PACKAGE_NAME}\"" \
        '$0 == dot_import { print named_import } { print }' "${OUTPUT_FILE}" > "${OUTPUT_FILE}.tmp"
    mv "${OUTPUT_FILE}.tmp" "${OUTPUT_FILE}"
fi
